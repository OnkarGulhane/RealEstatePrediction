import math
from rest_framework import serializers
from .models import Prediction


class PropertyPredictionInputSerializer(serializers.Serializer):
    schema_version = serializers.CharField(
        required=True,
        help_text="Contract schema version. Currently accepted version is strictly '1.0'."
    )
    location = serializers.CharField(
        required=True,
        min_length=1,
        max_length=150,
        help_text="Supported Indian residential property location / city."
    )
    sub_area = serializers.CharField(
        required=False,
        allow_null=True,
        allow_blank=True,
        default=None,
        max_length=150,
        help_text="Optional hyper-local neighborhood / sub-area (e.g. Kothrud, Baner, Wakad)."
    )
    area_value = serializers.FloatField(
        required=True,
        min_value=0.0001,
        help_text="Positive finite numerical property area in square feet."
    )
    area_basis = serializers.ChoiceField(
        choices=["CARPET", "SUPER"],
        required=True,
        help_text="Area measurement basis: 'CARPET' or 'SUPER'."
    )
    bhk = serializers.IntegerField(
        required=False,
        allow_null=True,
        min_value=1,
        max_value=20,
        default=None,
    )
    bathrooms = serializers.FloatField(
        required=False,
        allow_null=True,
        min_value=1.0,
        max_value=20.0,
        default=None,
    )
    balcony = serializers.IntegerField(
        required=False,
        allow_null=True,
        min_value=0,
        max_value=10,
        default=None,
    )
    floor_number = serializers.FloatField(
        required=False,
        allow_null=True,
        min_value=-2.0,
        max_value=200.0,
        default=None,
    )
    total_floors = serializers.FloatField(
        required=False,
        allow_null=True,
        min_value=1.0,
        max_value=200.0,
        default=None,
    )
    parking_spaces = serializers.IntegerField(
        required=False,
        allow_null=True,
        min_value=0,
        max_value=500,
        default=None,
        help_text="Number of car parking spaces (0 or positive whole-number count)."
    )
    furnishing = serializers.CharField(required=False, allow_null=True, allow_blank=True, default=None)
    transaction_type = serializers.CharField(required=False, allow_null=True, allow_blank=True, default=None)
    status = serializers.CharField(required=False, allow_null=True, allow_blank=True, default=None)
    facing = serializers.CharField(required=False, allow_null=True, allow_blank=True, default=None)
    ownership = serializers.CharField(required=False, allow_null=True, allow_blank=True, default=None)

    def validate_schema_version(self, value: str) -> str:
        if value.strip() != "1.0":
            raise serializers.ValidationError(
                f"Incompatible schema version '{value}'. Only version '1.0' is supported."
            )
        return value.strip()

    def validate_area_value(self, value: float) -> float:
        if not math.isfinite(value) or value <= 0:
            raise serializers.ValidationError("area_value must be a finite positive number.")
        return value

    def validate(self, attrs: dict) -> dict:
        floor_num = attrs.get("floor_number")
        total_floors = attrs.get("total_floors")
        if floor_num is not None and total_floors is not None:
            if floor_num > total_floors:
                raise serializers.ValidationError(
                    {"floor_number": f"floor_number ({floor_num}) cannot exceed total_floors ({total_floors})."}
                )
        return attrs


class PredictionResponseSerializer(serializers.ModelSerializer):
    property_summary = serializers.SerializerMethodField()
    disclaimer = serializers.SerializerMethodField()

    class Meta:
        model = Prediction
        fields = [
            "id",
            "estimated_price_inr",
            "currency",
            "model_version",
            "schema_version",
            "request_id",
            "created_at",
            "property_summary",
            "disclaimer",
        ]

    def get_property_summary(self, obj: Prediction) -> dict:
        return {
            "location": obj.location,
            "sub_area": obj.sub_area,
            "area_value": obj.area_value,
            "area_basis": obj.area_basis,
            "bhk": obj.bhk,
            "bathrooms": obj.bathrooms,
            "balcony": obj.balcony,
            "floor_number": obj.floor_number,
            "total_floors": obj.total_floors,
            "parking_spaces": obj.parking_spaces,
            "furnishing": obj.furnishing,
            "transaction_type": obj.transaction_type,
            "status": obj.status,
            "facing": obj.facing,
            "ownership": obj.ownership,
        }

    def get_disclaimer(self, obj: Prediction) -> str:
        return (
            "This estimate is generated by an offline-trained regression model based on historical listing data. "
            "It does not constitute a certified valuation or guaranteed market price."
        )
